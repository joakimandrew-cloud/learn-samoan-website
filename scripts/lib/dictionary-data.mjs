// Node-side loader for the dictionary's pages (Build-Spec part f of
// plans/2026-11-19-samoan-site-search-features.md). The React pages get the
// same data through src/premium/lib/dictionary-data.js; both call
// buildDictionaryIndex() in src/premium/lib/dictionary-pages.js, so a script
// and the site never disagree.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildDictionaryIndex, buildEntries, entryDropReason } from '../../src/premium/lib/dictionary-pages.js'

import { selectExamples } from '../../src/premium/lib/dictionary-examples.js'

// DICTIONARY_APP_ROOT points the data, the book copy and dist/ at another folder
// with the same layout (used to prove check:dictionary fails on broken data).
export const APP_ROOT = process.env.DICTIONARY_APP_ROOT
  ? path.resolve(process.env.DICTIONARY_APP_ROOT)
  : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
export const EXAMPLES_FILE = 'src/premium/data/dictionary-examples.json'

const readJson = (root, file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'))

export function chapterFile(number) {
  return `book/Chapter-${String(number).padStart(2, '0')}.md`
}

export function readDictionarySources(root = APP_ROOT) {
  return {
    glossary: readJson(root, 'src/data/glossary.json'),
    vocabulary: readJson(root, 'src/data/book-vocabulary.json'),
    chapters: readJson(root, 'src/data/chapters.json'),
  }
}

export function readChapters(root = APP_ROOT) {
  const chapters = {}
  for (let number = 1; ; number += 1) {
    const file = path.join(root, chapterFile(number))
    if (!fs.existsSync(file)) break
    chapters[number] = fs.readFileSync(file, 'utf8')
  }
  return chapters
}

// The example pairs, drawn fresh from the app's book copy.
export function drawExamples(root = APP_ROOT) {
  const entries = buildEntries(readDictionarySources(root))
  return selectExamples({ entries, chapters: readChapters(root) })
}

// The index as the site builds it, from the files on disk.
export function loadDictionaryIndex(root = APP_ROOT) {
  const examples = readJson(root, EXAMPLES_FILE).examples
  return buildDictionaryIndex({ ...readDictionarySources(root), examples })
}

export function examplesFileText(examples) {
  return `${JSON.stringify({
    note: 'Generated by scripts/build-dictionary-data.mjs from book/Chapter-NN.md. Each pair is one printed line of a chapter that teaches the entry or a later one. Do not edit by hand.',
    examples,
  }, null, 1)}\n`
}

// How many senses each rule kept out of the English pages (and how many
// leading "also" were stripped), for the build's own report.
export function englishDropCounts(index) {
  const counts = {}
  for (const item of index.englishDropped) counts[item.reason] = (counts[item.reason] || 0) + 1
  return { dropped: counts, alsoStripped: index.englishAlsoStripped }
}

export { entryDropReason }
